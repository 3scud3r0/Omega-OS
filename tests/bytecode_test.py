"""Admission rejects unsafe generated programs before a child is runnable."""
import ctypes as C
import struct,subprocess
subprocess.run(['gcc','-shared','-fPIC','-O2','-Wall','-Wextra','-Werror','-pedantic','-std=c99','-Iinclude','src/bytecode.c','src/rational.c','-o','build/bytecode.so'],check=True)
class Q(C.Structure):_fields_=[('num',C.c_longlong),('den',C.c_longlong)]
f=C.CDLL('./build/bytecode.so').bytecode_run;f.argtypes=[C.c_void_p,C.c_size_t,C.POINTER(Q)];f.restype=C.c_bool
push=lambda n,d=1:b'\1'+struct.pack('<2q',n,d)
def run(code,expected=None):
    cap=struct.pack('<2Q',0x3343424f,len(code))+code;out=Q();ok=f(cap,len(cap),C.byref(out));assert ok==(expected is not None)
    if ok:assert (out.num,out.den)==expected
run(push(1,3)+push(1,6)+b'\2\0',(1,2))
run(push(7)+push(2)+b'\5\6\0',(-7,2))
for code in [push(1)+push(0)+b'\5\0',push(1,0)+b'\0',push(2,4)+b'\0',push(2**63-1)+push(1)+b'\2\0',push(1)*33+b'\0',b'\xff',b'\1',push(1)+push(2)+b'\0',push(1)+b'\6'*255+b'\0']:
    run(code)
print('PASS generated bytecode: rational results, division by zero, overflow, canonical values, stack and gas limits')
